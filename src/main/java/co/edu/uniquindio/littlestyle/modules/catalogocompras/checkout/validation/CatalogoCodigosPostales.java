    /** Minúsculas, sin tildes y con espacios simples. */
    static String normalizar(String texto) {
        if (texto == null) {
            return "";
        }
        String sinTildes = Normalizer.normalize(texto, Normalizer.Form.NFD).replaceAll("\\p{M}", "");
        return sinTildes.toLowerCase(Locale.ROOT).trim().replaceAll("\\s+", " ");
    }

    /** Lista exacta de códigos del municipio, o vacío si aún no está catalogado. */
    public static Optional<List<String>> codigosDe(String departamento, String municipio) {
        return Optional.ofNullable(POR_MUNICIPIO.get(normalizar(departamento) + "|" + normalizar(municipio)));
    }

    /** Prefijo postal del departamento, o vacío si el nombre no se reconoce. */
    public static Optional<String> prefijoDe(String departamento) {
        return Optional.ofNullable(PREFIJO_POR_DEPARTAMENTO.get(normalizar(departamento)));
    }

    /**
     * Resultado de comprobar un código postal contra su ubicación.
     */
    public enum Resultado { VALIDO, NO_CORRESPONDE_AL_DEPARTAMENTO, NO_CORRESPONDE_AL_MUNICIPIO }

    /** Comprueba que el código sea coherente con el departamento y el municipio. */
    public static Resultado validar(String departamento, String municipio, String codigoPostal) {
        if (codigoPostal == null) {
            return Resultado.VALIDO;
        }
        Optional<String> prefijo = prefijoDe(departamento);
        if (prefijo.isPresent() && !codigoPostal.startsWith(prefijo.get())) {
            return Resultado.NO_CORRESPONDE_AL_DEPARTAMENTO;
        }
        Optional<List<String>> lista = codigosDe(departamento, municipio);
        if (lista.isPresent() && !lista.get().contains(codigoPostal)) {
            return Resultado.NO_CORRESPONDE_AL_MUNICIPIO;
        }
        return Resultado.VALIDO;
    }
