/** Resultado de comprobar un código postal contra su ubicación. */
export type ResultadoCodigoPostal = 'valido' | 'departamento' | 'municipio';

/**
 * Prefijo postal (dos primeros dígitos) de un departamento; coincide con su código DANE.
 * @param departamento Nombre exacto del departamento del catálogo.
 * @returns Prefijo, o `null` si el departamento no existe.
 */
export function prefijoPostalDe(departamento: string): string | null {
  return MUNICIPIOS_COLOMBIA.find((m) => m.departamento === departamento)?.departamentoDane ?? null;
}

/**
 * Lista de códigos postales existentes en un municipio.
 * @returns Los códigos, o `null` si el municipio aún no tiene lista en el catálogo local.
 */
export function codigosPostalesDe(departamento: string, municipio: string): readonly string[] | null {
  const registro = MUNICIPIOS_COLOMBIA.find(
    (m) => m.departamento === departamento && m.municipio === municipio,
  );
  return registro ? CODIGOS_POSTALES_POR_MUNICIPIO_DANE[registro.municipioDane] ?? null : null;
}

/** Comprueba que el código sea coherente con el departamento y el municipio elegidos. */
export function validarCodigoPostal(
  departamento: string,
  municipio: string,
  codigo: string,
): ResultadoCodigoPostal {
  const prefijo = prefijoPostalDe(departamento);
  if (prefijo && !codigo.startsWith(prefijo)) return 'departamento';
  const lista = codigosPostalesDe(departamento, municipio);
  if (lista && !lista.includes(codigo)) return 'municipio';
  return 'valido';
}

/**
 * Validador del control `codigoPostal`: lee `departamento` y `municipio` de su formulario padre.
 * Debe revalidarse al cambiar la ubicación (los formularios reinician el código al cambiarla).
 */
export function codigoPostalCoherente(control: AbstractControl): ValidationErrors | null {
  const codigo = String(control.value ?? '').trim();
  const grupo = control.parent;
  if (!codigo || !grupo) return null;
  const resultado = validarCodigoPostal(
    String(grupo.get('departamento')?.value ?? ''),
    String(grupo.get('municipio')?.value ?? ''),
    codigo,
  );
  return resultado === 'valido' ? null : { codigoPostalIncoherente: resultado };
}
